#!/usr/bin/env python3
"""Exact formulas for few columns (`formula_m<m>.json`) and exact values for few rows (`fixed_n.csv`).

    .venv/bin/python scripts/small_formulas_data.py <max_m>      # needs build/cpp/gradient_bound
    .venv/bin/python scripts/small_formulas_data.py tex          # writes small_tables.tex to $ARTICLE_DIR
    .venv/bin/python scripts/small_formulas_data.py md           # data/small/formulas.md and exact_values.md

Every number is an exact rational; the fit for each `m` is checked on further values of `n`.
"""
# SPDX-License-Identifier: MIT
import csv
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src" / "python"))

from gradient_key.small_formulas import (  # noqa: E402
    engine_excess_numerator,
    exact_values_md,
    formulas_md,
    falling,
    formula_for,
    formula_tex,
    load_formula,
    table_m_tex,
    table_n_tex,
)

DATA = ROOT / "data" / "small"
ENGINE = ROOT / "build" / "cpp" / "gradient_bound"
MAX_ROWS = 5  # the engine takes at most 33 columns


def main(max_m: int) -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    for m in range(2, max_m + 1):
        out = formula_for(m, ENGINE)
        (DATA / f"formula_m{m}.json").write_text(json.dumps(out, indent=1) + "\n")
        print(m, out["leading"], len(out["coefficients"]), flush=True)
    with open(DATA / "fixed_n.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["n", "m", "excess_numerator", "excess_denominator"])
        for n in range(1, MAX_ROWS + 1):
            for m in range(2, 2**n + 1):
                num = engine_excess_numerator(n, m, ENGINE) / falling(2**n, m)
                w.writerow([n, m, num.numerator, num.denominator])


def tex() -> None:
    art = Path(os.environ.get("ARTICLE_DIR", ROOT.parent / "gradient-key"))
    parts = ["% Generated by scripts/small_formulas_data.py tex; do not edit."]
    for m in (4, 5, 6):
        parts.append(r"\newcommand{\smallformula%s}{%s}" % ("".join("four five six".split()[m - 4:m - 3]), formula_tex(m, load_formula(DATA, m))))
    (art / "small_formulas.tex").write_text("\n".join(parts) + "\n")
    (art / "small_table_m.tex").write_text(table_m_tex(DATA, range(4, 13)))
    (art / "small_table_n.tex").write_text(table_n_tex(DATA / "fixed_n.csv"))


def md() -> None:
    (DATA / "formulas.md").write_text(formulas_md(DATA, range(2, 13)))
    (DATA / "exact_values.md").write_text(exact_values_md(ROOT / "data" / "gradient-bound" / "exact_formula.csv", 12, 13))


if __name__ == "__main__":
    if sys.argv[1:] == ["tex"]:
        tex()
    elif sys.argv[1:] == ["md"]:
        md()
    else:
        main(int(sys.argv[1]))
